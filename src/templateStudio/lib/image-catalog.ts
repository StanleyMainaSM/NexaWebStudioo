export function getImagesForIndustry(industry: string, count: number): { src: string, alt: string }[] {
  const normalized = industry.toLowerCase();
  
  let key = 'default';
  if (normalized.includes('restaurant') || normalized.includes('food') || normalized.includes('cafe') || normalized.includes('bakery')) {
    key = 'restaurant';
  } else if (normalized.includes('saas') || normalized.includes('software') || normalized.includes('startup') || normalized.includes('app')) {
    key = 'saas';
  } else if (normalized.includes('law') || normalized.includes('legal') || normalized.includes('attorney')) {
    key = 'law';
  } else if (normalized.includes('real estate') || normalized.includes('property') || normalized.includes('broker')) {
    key = 'real_estate';
  } else if (normalized.includes('hotel') || normalized.includes('hospitality') || normalized.includes('travel') || normalized.includes('resort')) {
    key = 'hotel';
  } else if (normalized.includes('fashion') || normalized.includes('clothing') || normalized.includes('apparel') || normalized.includes('boutique')) {
    key = 'fashion';
  } else if (normalized.includes('fitness') || normalized.includes('gym') || normalized.includes('health') || normalized.includes('training')) {
    key = 'fitness';
  } else if (normalized.includes('architecture') || normalized.includes('construction') || normalized.includes('design') || normalized.includes('interior')) {
    key = 'architecture';
  } else if (normalized.includes('tech') || normalized.includes('it') || normalized.includes('cyber') || normalized.includes('data')) {
    key = 'technology';
  } else if (normalized.includes('agency') || normalized.includes('marketing') || normalized.includes('consulting') || normalized.includes('business') || normalized.includes('corporate')) {
    key = 'agency';
  } else if (normalized.includes('agriculture') || normalized.includes('farm') || normalized.includes('nature') || normalized.includes('eco')) {
    key = 'nature';
  }
  
  const pool = IMAGE_CATALOG[key] || IMAGE_CATALOG.default;
  
  // Return random unique images from the pool
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count).map((src, i) => ({
    src,
    alt: `${industry} image ${i + 1}`
  }));
}
